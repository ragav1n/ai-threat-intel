"""
Convert the PRISM IOC-extraction benchmark into the project's dataset schema.

PRISM (Feraudo et al., arXiv 2506.11325, "Revealing the True Indicators:
Understanding and Improving IoC Extraction From Threat Reports", 2025) is an
open, fully human-validated benchmark: 1,791 indicators across 50 real-world
threat reports, each tagged IoC or nonIoC. It is the external GOLD benchmark
for IOC extraction — labels were resolved by senior analysts, not generated by
an LLM — and was purpose-built for comparing IOC-extraction systems.

This script reads a local clone of github.com/EvanFr/LANCE and emits a single
JSON file in the project's standard {"samples": [...]} schema:

    git clone https://github.com/EvanFr/LANCE
    python scripts/build_prism_dataset.py --prism-dir LANCE/PRISM \
        --output data/evaluation/prism_benchmark.json

Each emitted sample carries:
  expected_iocs — indicators PRISM labelled "IoC"   (the extraction targets)
  decoy_iocs    — indicators PRISM labelled "nonIoC" (IOC-shaped but benign;
                  preserved for honest precision analysis — load_samples()
                  ignores this field, the standard schema only needs the IoCs)

PRISM is GPL-3.0; the generated file is a derivative work. Keep attribution to
the PRISM authors and do not relicense it.
"""
import argparse
import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO_ROOT)

from threat_intel_aggregator.evaluation.dataset_builder.validation import (
    format_grounding_report, grounding_report,
)

# PRISM type vocabulary -> the IOCType values the extractor emits.
_PRISM_TYPE = {"fqdn": "domain", "ip4": "ip", "url": "url", "cve": "cve"}
# PRISM uses a single "hash" type; recover the algorithm from the digest length.
_HASH_BY_LEN = {32: "md5", 40: "sha1", 64: "sha256"}


def _canon_type(value: str, ptype: str) -> str:
    """Map a PRISM (value, type) pair to the project's canonical IOC type."""
    ptype = ptype.strip().lower()
    if ptype == "hash":
        return _HASH_BY_LEN.get(len(value.strip()), "hash")
    return _PRISM_TYPE.get(ptype, ptype)


def build(prism_dir: str) -> list:
    """Read a LANCE/PRISM directory and return standard-schema sample dicts."""
    gt_path = os.path.join(prism_dir, "GT.json")
    reports_dir = os.path.join(prism_dir, "ReportsJSON")
    with open(gt_path) as f:
        gt = json.load(f)

    samples = []
    for report_key, entry in gt.items():
        report_path = os.path.join(reports_dir, entry["filename"] + ".json")
        with open(report_path) as f:
            text = json.load(f).get("plain_text", "")

        expected, decoys = [], []
        for value, meta in entry["indicators"].items():
            ioc = {"value": value, "type": _canon_type(value, meta["type"])}
            (expected if meta["label"] == "IoC" else decoys).append(ioc)

        samples.append({
            "id": f"prism_{report_key}",
            "text": text,
            "expected_iocs": expected,
            "decoy_iocs": decoys,
            "category": "true_positive",
            "source": "PRISM (arXiv:2506.11325, GPL-3.0)",
        })
    return samples


def main() -> None:
    ap = argparse.ArgumentParser(description="Convert PRISM into the dataset schema.")
    ap.add_argument("--prism-dir", required=True,
                    help="Path to the PRISM directory of a LANCE clone")
    ap.add_argument("--output", default="data/evaluation/prism_benchmark.json")
    args = ap.parse_args()

    samples = build(args.prism_dir)
    n_ioc = sum(len(s["expected_iocs"]) for s in samples)
    n_decoy = sum(len(s["decoy_iocs"]) for s in samples)

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w") as f:
        json.dump({"samples": samples}, f, indent=1)

    print(f"PRISM -> {args.output}")
    print(f"  reports        : {len(samples)}")
    print(f"  IoC labels     : {n_ioc}  (extraction targets)")
    print(f"  nonIoC decoys  : {n_decoy}  (preserved as decoy_iocs)")
    print()
    print(format_grounding_report(grounding_report(samples)))


if __name__ == "__main__":
    main()
